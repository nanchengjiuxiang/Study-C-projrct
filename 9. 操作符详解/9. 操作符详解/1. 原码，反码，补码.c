#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>

int main()
{
	/*正整数的原、反、补码都相同。
	负整数的三种表示方法各不相同。*/


	int a = -13;//1101
	//10000000000000000000000000001101-原码
	//11111111111111111111111111110010-反码
	//11111111111111111111111111110011-补码


	int b = 13;//1101
	//00000000000000000000000000001101-原码
	//01111111111111111111111111110010-反码
	//01111111111111111111111111110011-补码

	unsigned int c = 13;
	//00000000000000000000000000001101-原码
	//01111111111111111111111111110010-反码
	//01111111111111111111111111110011-补码


//对于整形来说:数据存放内存中其实存放的是补码
//在计算机系统中, 数值一律用补码来表示和存储。原因在于, 使用补码, 可以将符号位和数值域统一处理;
//同时, 加法和减法也可以统一处理(CPU只有加法器)此外, 补码与原码相互转换, 其运算过程是相同的, 不需要
//额外的硬件电路。

	return 0;
}