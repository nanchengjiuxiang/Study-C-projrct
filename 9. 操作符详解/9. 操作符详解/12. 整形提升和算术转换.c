#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>

int main()
{
	/*C语言中整型算术运算总是至少以缺省(默认)整型型的精度来进行的。
	为了获得这个精度, 表达式中的字符和短整型操作数在使用之前被转换为普通整型, 这种转换称为整型提升。*/

	/*整型提升的意义:
	表达式的整型运算要在CPU的相应运算器件内执行, CPU内整型运算器(ALU)的操作数的字节长度一般就是int的字节长度, 同时也是CPU的通用寄存器的长度。
	因此, 即使两个char类型的相加, 在CPU执行时实际上也要先转换为CPU内整型操作数的标准长度。
	通用CPU(general - purpose CPU)是难以直接实现两个8比特字节直接相加运算(虽然机器指令中可能有这种字节相加指令)。
	所以, 表达式中各种长度可能小于int长度的整型值, 都必须先转换为int或unsigned int, 然后才能送入CPU去执行运算。*/


	char a = 10;
	//00000000000000000000000000001010
	//a = 00001010  --> 截断
	char b = 120;
	//00000000000000000000000001111000
	//b = 01111000
	char c = 0;
	c = a + b;
	//整形提升：a = 00000000000000000000000000001010    b = 00000000000000000000000001111000
	//c = 000000000000000000000010000010 ---> 截断：c = 10000010 
	
	printf("c = %d\nc = %c\n", c);
	//使用%d打印时会导致字符c整形提升，结果为：11111111111111111111111110000010（负数以补码的形式存储）
	//c的原码：10000000000000000000000001111110





	/*如果某个操作符的各个操作数属于不同的类型, 那么除非其中一个操作数的转换为另一个操作数的类型, 否则操作
	就无法进行。下面的层次体系称为寻常算术转换。*/




	return 0;
}