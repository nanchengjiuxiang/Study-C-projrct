#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>

// & --> 按位与
// | --> 按位或
// ^ --> 按位异或
// ~ --> 按位取反

int main()
{
	int a = 10;  //00000000000000000000000000001010  补码
	int b = -7;  //11111111111111111111111111111001  补码

	//按位与：对应的二进制位，有0则为0，同时为1才为1
	int c = a & b;  //00000000000000000000000000001000  --> 正数，补码与原码相同 --- 代表 8
	printf("c = %d\n", c);


	//按位或：对应的二进制位，有1则为01同时为0才为0
	int d = a | b;  //11111111111111111111111111111011  --> 负数   原码: 10000000000000000000000000000101 --- 代表 -5
	printf("d = %d\n", d);


	//按位异或：对应的二进制位，相同为0，相异为1
	int e = a ^ b;  //11111111111111111111111111110011  --> 负数   原码: 10000000000000000000000000001101 --- 代表 -13
	printf("e = %d\n", e);


	//按位取反：
	int num = 0;  //00000000000000000000000000000000
	printf("~num = %d\n", ~num);  //11111111111111111111111111111111 ---> 原码：10000000000000000000000000000001

	return 0;
}