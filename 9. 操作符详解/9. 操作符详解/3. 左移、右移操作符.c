#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>

int main()
{
	//移位操作符的操作数只能为整数

	/*左移操作符
	移位规则 : 左边抛弃、右边补0*/

	int a = -10;  //10000000000000000000000000001010 --> 原码  11111111111111111111111111110110 --> 补码
	int b = a << 1;  //移动的是补码的二进制位  --- 11111111111111111111111111101100  ---> 代表 -20 的补码
	printf("a = %d b = %d\n", a, b);   //打印的是原码的值 b = 100000000000000000000000000010100


	/*右移操作符
	移位规则 : 首先右移运算分两种:
	1. 逻辑右移 : 左边用0填充, 右边丢弃
	2. 算术右移 : 左边用原该值的符号位填充, 右边丢弃（大部分）*/

	int num = -10;
	int num2 = num >> 1;  //移动的是补码的二进制位  --- 11111111111111111111111111111011  ---> 代表 -5 的补码
	printf("num = %d num2 = %d\n", num, num2);   //num2 = 100000000000000000000000000000101


	return 0;
}